# Eligible or Not 
age = int(input("Enter your age:"))
if age>=18:
     print("You are eligible to vote.")
else:
     print("Not eligible.")

# Marks and Grade 

marks = int(input("enter your marks :"))

if marks>=90:
     print("Grade A")
elif marks>=75:
     print("Grade B")
elif marks>=60:
     print("Grade C")
else:
     print("Fail")
